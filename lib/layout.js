/**
 * 面板参数的唯一来源。
 *
 * 为什么单独一个文件：宿主（DSH Desktop）读这里的值决定业务区与会话区怎么分，
 * 客户端外壳读同一份值渲染顶栏。如果两边各写一遍，改一处忘一处就会出现
 * 「顶栏说有 AI 按钮、面板其实没开」这种只能靠肉眼发现的错。
 *
 * customFrame: true 的含义：宿主不再替我们排「左业务右会话」的标准分栏，
 * 整块画布交给插件，会话节点由我们自己挂载、自己控制显隐与宽度拖动。
 * 代价是顶栏、避让窗口按钮（macOS 红绿灯）、窄屏收起都要自己写对。
 */

export const PANEL = Object.freeze({
  /** 市场与装机列表里显示的名字 */
  title: '头颈癌工作台',
  /** 一句话说明：患者视角，不写科室视角 */
  description:
    '原发部位决定一切：把手术与放疗的功能代价、气管造口护理、放疗后长期毒性和复诊准备理清楚',
  repository: 'https://github.com/xyb-openharness-dsh-plugins/head-neck-workbench',

  /** 宿主把整块画布交给插件（顶栏 AI 按钮、会话区可拖） */
  customFrame: true,
  /** 业务区占画布宽度的比例。家族取值 0.6–0.7，头颈癌 34 个二级页签信息密度高，取上限侧 */
  businessWidth: 0.72,
  /** 窄于此宽度时收起会话区，只留业务区（单位 px） */
  collapseBelow: 900,
})

/**
 * 右侧会话区可拖动的宽度区间，单位是「占画布宽度的百分比」。
 * 下限保证输入框与消息气泡不挤成一条；上限留给业务区足够宽度。
 * 家族取值 25%–45%。
 */
export const AGENT_PANE = Object.freeze({
  min: 25,
  max: 45,
  /** 首次打开、且没有记住用户上次拖动位置时的宽度 */
  default: 32,
})

/** 顶栏高度（px）。会话区与业务区的滚动容器都从这里开始算。 */
export const TOP_BAR_HEIGHT = 52
